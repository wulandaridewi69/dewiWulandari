export const iconNames = Object.keys(paths);

export function Icon({ name, className, size = 16, strokeWidth = 1.75 }) {
  const glyph = paths[name];

  // Defensive: an unknown name renders nothing rather than crashing the tree.
  if (!glyph) return null;

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={cn('shrink-0', className)}
    >
      {glyph}
    </svg>
  );
}